def reduce(n):
    while n > 9:
        n = sum(int(d) for d in str(n))
    return n

def get_model(birth_day):
    return birth_day if 1 <= birth_day <= 31 else reduce(birth_day)

def get_year(birth_day, birth_month, current_year):
    return reduce(reduce(birth_day) + reduce(birth_month) + reduce(current_year))

def get_month(personal_year, current_month):
    return reduce(personal_year + reduce(current_month))

def get_day(personal_month, current_day):
    return reduce(personal_month + reduce(current_day))
